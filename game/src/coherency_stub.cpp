// GPU->CPU coherency for render-to-texture data the game's CPU code reads (the jsdk version of resolve_coherency.cpp).
//
// WWE '13 composites some wrestler textures on the GPU (retro Shawn Michaels in Attitude Era chapter 1): it renders
// 2048x1024 layers, resolves them into guest memory, then untiles/converts them on the CPU with XGUntileSurface
// (sub_82BE19E8). The GPU keeps resolve results in its own copy of guest memory, so without a read-back the CPU untiles
// stale memory and the model renders black with coloured stripes. This hook reads back only the source surface of each
// untile (load time). Reading back every resolve (readback_resolve_override=3) fixes it too, at a third of the frame rate.
//
// Opt-in: WWE13_UNTILE_COHERENCY=1 (alone it is not enough with the native renderer: its resolve results are not in
// the GPU's copy of memory either; the attire read-back window in jsdk xboxkrnl_io.cpp is what fixes it). Hand-written; not generated by ReXGlue.
#include <dlfcn.h>
#include <cstdint>
#include <cstdlib>

#include <rex/graphics/graphics_system.h>
#include <rex/graphics/command_processor.h>
#include <rex/logging.h>
#include <rex/runtime.h>
#include <rex/system/kernel_state.h>
#include <rex/system/xmemory.h>
#include "rex_compat.h"

// XGUntileSurface(dest=r3, row_pitch=r4, point=r5, source=r6, width=r7, height=r8, rect=r9, texel_pitch=r10). The tiled
// source spans align32(width) * align32(height) * texel_pitch bytes.
void wwe13_untile_coherency(PPCRegister& source, PPCRegister& width, PPCRegister& height, PPCRegister& texel_pitch) {
  static const bool enabled = [] {
    const char* v = std::getenv("WWE13_UNTILE_COHERENCY");
    return v && v[0] == '1';  // off by default: the attire read-back window (xboxkrnl_io.cpp) does this job
  }();
  if (!enabled) return;
  const uint64_t size = uint64_t((width.u32 + 31) & ~31u) * ((height.u32 + 31) & ~31u) * texel_pitch.u32;
  if (!size || size > 64u * 1024 * 1024) return;
  // Only GPU-made surfaces (render targets are at least 256 wide); small untiles are file data the CPU already has.
  if (width.u32 < 256 || height.u32 < 256) return;
  auto* kernel_state = REX_KERNEL_STATE();
  auto* graphics = kernel_state ? static_cast<rex::graphics::GraphicsSystem*>(kernel_state->emulator()->graphics_system())
                                : nullptr;
  auto* cp = graphics ? graphics->command_processor() : nullptr;
  if (!cp) return;
  const uint32_t address = kernel_state->memory()->GetPhysicalAddress(source.u32);
  if (address == UINT32_MAX) return;
  const uint32_t length = uint32_t(size);
  using Fn = int (*)(void*, uint32_t, uint32_t);
  static const Fn fn = [] {
    void* f = dlsym(RTLD_DEFAULT, "wwe13_readback_range_for_cpu");
    if (!f) {
      if (void* lib = dlopen("librexgpu-xenos.so", RTLD_NOW | RTLD_NOLOAD)) f = dlsym(lib, "wwe13_readback_range_for_cpu");
    }
    return reinterpret_cast<Fn>(f);
  }();
  if (!fn) {
    static bool warned = false;
    if (!warned) REXLOG_WARN("[wwe13][untile] wwe13_readback_range_for_cpu not found in the GPU plugin");
    warned = true;
    return;
  }
  if (!fn(cp, address, length)) REXLOG_WARN("[wwe13][untile] read-back of 0x{:08X} ({} bytes) failed", address, length);
}
